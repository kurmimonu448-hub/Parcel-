export const DEFAULT_PAYOUT_MODEL = PayoutModel.HYBRID;

export function calculateDeliveryFee(planTier: PlanTier, distanceKm: number): number {
  const plan = SUBSCRIPTION_PLANS[planTier];
  const base = plan.perDeliveryFee;
  if (distanceKm <= 3) return base;
  const extraKm = Math.ceil(distanceKm - 3);
  return base + extraKm * 5;
}
